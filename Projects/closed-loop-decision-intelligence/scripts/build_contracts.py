"""Regenerate reviewed SQL/dbt contracts from the relational schema and shared SQL.

Run from repository root: python -m scripts.build_contracts
"""
import re

import yaml
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from src.common import models as m
from src.common.config import ROOT
from src.common.db import SCHEMAS


def write(path, text):
    destination = ROOT / path
    destination.parent.mkdir(parents=True, exist_ok=True)
    normalized = "\n".join(line.rstrip() for line in text.splitlines()).rstrip() + "\n"
    destination.write_text(normalized, encoding="utf-8", newline="\n")


def build():
    dialect = postgresql.dialect()
    statements = [f"CREATE SCHEMA IF NOT EXISTS {name};" for name in SCHEMAS]
    for table in m.metadata.sorted_tables:
        statements.append(str(CreateTable(table, if_not_exists=True).compile(dialect=dialect))+";")
        for index in table.indexes:
            statements.append(str(CreateIndex(index, if_not_exists=True).compile(dialect=dialect))+";")
    write("database/init/001_warehouse.sql", "-- Generated by scripts/build_contracts.py\n"+"\n".join(statements))
    ledger = (ROOT / "database/migrations/002_ledger.sql").read_text()
    write("database/init/002_ledger.sql", ledger+";\n")
    sources = {"version": 2, "sources": [{"name": "operational", "schema": "raw", "tables": []}]}
    models = {"version": 2, "models": []}
    for table in m.RAW_TABLES:
        sources["sources"][0]["tables"].append({"name": str(table.name),
            "columns": [{"name": "id", "data_tests": ["unique", "not_null"]}]})
        write(f"dbt/models/staging/stg_{table.name}.sql",
              "SELECT * FROM {{ source('operational', '"+table.name+"') }}\n")
        columns = [{"name": "id", "data_tests": ["unique", "not_null"]}]
        for fk in table.foreign_keys:
            columns.append({"name": str(fk.parent.name), "data_tests": ["not_null",
                {"relationships": {"arguments": {"to": "ref('stg_"+fk.column.table.name+"')", "field": "id"}}}]})
        models["models"].append({"name": f"stg_{table.name}", "columns": columns})
    query = (ROOT / "sql/analytics/cohort_mart.sql").read_text()
    query = re.sub(r"raw\.(\w+)", lambda match: "{{ ref('stg_"+match[1]+"') }}", query)
    write("dbt/models/intermediate/int_cohort_activity.sql", query)
    write("dbt/models/marts/cohort_mart.sql", "SELECT * FROM {{ ref('int_cohort_activity') }}\n")
    models["models"].append({"name": "cohort_mart", "columns": [
        {"name": "id", "data_tests": ["unique", "not_null"]},
        {"name": "timestamp", "data_tests": ["not_null"]}, {"name": "revenue", "data_tests": ["not_null"]}]})
    for source, name in [("orders", "fact_orders"), ("web_sessions", "fact_sessions"),
                         ("payments", "fact_payments"), ("marketing_campaigns", "fact_marketing"),
                         ("support_tickets", "fact_support"), ("customers", "dim_customer"),
                         ("products", "dim_product")]:
        write(f"dbt/models/marts/{name}.sql", "SELECT * FROM {{ ref('stg_"+source+"') }}\n")
    for field in ["country", "channel"]:
        write(f"dbt/models/marts/dim_{field}.sql", "SELECT DISTINCT "+field+" FROM {{ ref('stg_web_sessions') }}\n")
    write("dbt/models/marts/dim_date.sql", "SELECT DISTINCT CAST(timestamp AS date) AS date,\n"
          "EXTRACT(YEAR FROM timestamp) AS year, EXTRACT(MONTH FROM timestamp) AS month,\n"
          "EXTRACT(ISODOW FROM timestamp) AS weekday FROM {{ ref('stg_web_sessions') }}\n")
    from src.metrics.engine import registry
    expressions = []
    for metric in registry():
        if metric.aggregation == "distinct_count":
            expression = "MAX(c.active_customers)"
        else:
            expression = f"SUM(m.{metric.numerator})"
            if metric.denominator:
                expression = f"1.0 * {expression} / NULLIF(SUM(m.{metric.denominator}), 0)"
            if metric.complement:
                expression = f"1.0 - ({expression})"
        expressions.append(f"  {expression} AS {metric.metric_id}")
    daily_sql = ("WITH customers AS (SELECT CAST(timestamp AS date) AS date, COUNT(DISTINCT customer_id) AS active_customers\n"
        " FROM {{ ref('stg_orders') }} WHERE status='PAID' GROUP BY CAST(timestamp AS date))\n"
        "SELECT CAST(m.timestamp AS date) AS date,\n" + ",\n".join(expressions) +
        "\nFROM {{ ref('cohort_mart') }} m LEFT JOIN customers c ON c.date=CAST(m.timestamp AS date)\n"
        "GROUP BY CAST(m.timestamp AS date)\n")
    write("dbt/models/marts/daily_company_metrics.sql", daily_sql)
    models["models"].append({"name": "daily_company_metrics", "columns": [{"name": "date", "data_tests": ["unique", "not_null"]}]})
    write("dbt/models/staging/sources.yml", yaml.safe_dump(sources, sort_keys=False))
    write("dbt/models/schema.yml", yaml.safe_dump(models, sort_keys=False))
    for folder in ["data/raw", "data/generated", "data/exports", "data/samples", "database/seeds",
                   "sql/investigations", "sql/monitoring", "notebooks/exploration", "n8n/credentials_examples"]:
        write(folder+"/.gitkeep", "")


if __name__ == "__main__":
    build()
